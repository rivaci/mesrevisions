// Pièges — famille « Lumière et son » (chapitre 9 : vitesse de propagation de
// la lumière et du son).
//
// Un piège n'est pas une erreur constatée : c'est une CONCEPTION documentée.
// L'élève ne se trompe pas au hasard, il applique un modèle qui prédit
// correctement la quasi-totalité de ce qu'il a vécu — et c'est exactement ce
// qui le rend coûteux à déloger. Le catalogue dit ce que l'élève croit, d'où on
// le sait, et par quel dispositif on met le modèle en défaut.
//
// ── Pourquoi ces trois-là ──────────────────────────────────────────────────
//
// Elles sont les trois entrées « Signaux » du catalogue de `charte.md`, et les
// deux premières ne sont pas périphériques au programme : les deux premiers
// savoir-faire du chapitre 9 de `programme.md` — « Distinguer une source
// primaire d'un objet diffusant » et « Énoncer les conditions de visibilité
// d'un objet » — sont exactement l'objet de l'extramission et du refus de la
// diffusion (`didactique.md` § 9, point 6). L'extramission porte en plus le
// résultat central de tout le dossier : une leçon réfutationnelle sur la
// vision produit un effet mesurable au post-test immédiat chez des élèves de
// 13-14 ans, et plus rien à trois-cinq mois (`didactique.md` § 2.2 et § 7 ①).
// C'est ce résultat qui décide de l'architecture espacée ; le piège qui le
// porte ne peut pas être écrit à la légère.
//
// ── Les rangs : un seul des trois est une reprise de didactique.md § 7 ──────
//
// `rang` est défini comme la reprise littérale du § 7. Il faut donc dire quels
// rangs le sont et lesquels ne le sont pas, sinon le champ ment.
//
//   • `extramission` — rang 1, reprise littérale (§ 7, rang 1, entrée ①).
//     C'est la seule des trois dont la persistance a été MESURÉE après un
//     enseignement qui la visait explicitement. `fiabilite: primaire` : les
//     deux articles (Cottrell & Winer 1994, Winer et al. 2002) sont marqués ✔
//     dans `didactique.md`, lus en original.
//
//   • `objets-ordinaires-ne-diffusent-pas` — rang 3, et le rang 1 d'une
//     version précédente a été REFUSÉ en relecture. Le § 7 ne range cette
//     conception NULLE PART ; § 6.3 la documente qualitativement (Guesne 1985)
//     sans un seul chiffre, et § 8 la classe explicitement ○, « aucun
//     chiffre ». Le rang 1 s'appuyait sur une inférence, honnêtement nommée :
//     la leçon réfutationnelle de Winer enseignait la chaîne de vision sur un
//     objet NON LUMINEUX, dont la diffusion est la seconde jambe. Mais les
//     items de Winer mesurent ce qui SORT DE L'ŒIL, pas ce qui repart de
//     l'objet : la persistance de CE refus-là n'a jamais été mesurée. Le
//     critère du § 7 est strict — « persistance mesurée après un enseignement
//     qui la visait explicitement » — et une inférence n'est pas une reprise
//     littérale. Comme pour le son ci-dessous, le rang 3 N'AFFIRME PAS que la
//     conception cède à cet âge : personne n'en sait rien. Il dit que nous ne
//     dépensons pas sur elle le budget de réfutation espacée d'un rang 1 tant
//     qu'aucune donnée de persistance n'existe.
//     La conséquence est chère et elle est écrite : le piège sort de la file
//     annuelle et ses cinq re-confrontations tombent, alors qu'il porte les
//     deux premiers savoir-faire du chapitre 9. C'est le prix du critère, pas
//     un jugement sur l'importance de la conception. Condition de révision :
//     le gisement IOPSpark (§ 10, « lumière séparée de la vision ») ou le
//     dépouillement des situations CEDRE 2.11 et 2.16 (§ 10). Ses dispositifs
//     restent écrits au format exigé d'un rang 1 — deux constats de contextes
//     distincts, plus un contre-modèle d'un troisième décor — donc relever le
//     rang ne demandera aucune réécriture. `fiabilite: non-documente` porte,
//     lui, le statut réel de la conception — avec la conséquence de charte
//     qu'un piège non documenté ne fonde jamais à lui seul une décision de
//     maîtrise.
//
//   • `son-matiere-transportee` — rang 3 pour la même raison, et sans même
//     l'inférence : § 6.4 marque la robustesse ○ avec la mention « aucune
//     donnée sur l'évolution avec l'enseignement, aucune donnée française », et
//     § 8 range le son parmi les trous du corpus. Là encore le rang 3
//     N'AFFIRME PAS que la conception cède à cet âge. Condition de révision :
//     le gisement IOPSpark (§ 10, « son dans le vide ») ou l'instrument SCII,
//     s'ils sont un jour dépouillés. Dispositifs déjà au format d'un rang 1,
//     pour la même raison.
//
// Ces deux rangs 3 sont les seuls champs du fichier qui valent décision
// opérationnelle et non lecture du § 7, et ils sont signalés comme tels.
//
// Le seul chiffre solide du dossier sur le son — la part d'énoncés associant
// le son à des propriétés matérielles chez des collégiens taïwanais — reste
// dans `didactique.md` et ne figure nulle part dans ce qui est servi à
// l'élève. C'est la règle de sourçage, et c'est ce qui a manqué à l'épisode du
// « 57 % d'ampèremètre ». La règle vaut aussi pour les valeurs physiques : la
// comparaison des vitesses du son selon le milieu se dit ici EN MOTS, et les
// valeurs mesurées vivent dans la table de constantes sourcée, d'où les items
// de classe A′ les tirent. Un piège n'est pas l'endroit où l'on écrit un
// nombre en dur.
//
// Ce que cette règle interdit, exactement : toute valeur MESURÉE — une
// fréquence, une vitesse, une durée de propagation, une proportion. Elle
// n'interdit pas les nombres de décor (« vingt minutes dans une cave », « à
// quelques mètres »), qui ne sont la mesure de rien et qu'aucune table ne peut
// fournir. La distinction n'est pas cosmétique, et elle est écrite parce
// qu'elle avait déjà été manquée ici : une première rédaction du raisonnement
// `quelque-chose-arrive-bien` disait « ton tympan est poussé puis tiré des
// centaines de fois par seconde », c'est-à-dire une FRÉQUENCE, en dur, dans un
// texte servi à l'élève, quelques lignes après que l'en-tête l'a interdit.
//
// ── La famille sans constat ────────────────────────────────────────────────
//
// On ne peut pas faire constater à l'écran que rien ne sort de l'œil : il n'y
// a pas d'observation possible du non-événement. Pour `extramission`,
// `constats` est donc VIDE et le dispositif principal est le contre-modèle
// exécuté — le modèle de l'élève tourné jusqu'à sa prédiction, qui est ensuite
// confrontée à ce que l'élève sait déjà. TROIS exécutions, de décors
// différents : deux suffiraient à l'invariant 14, mais un rang 1 est
// re-confronté quatre à cinq fois par an et le moteur ne sert jamais deux fois
// le même dispositif — à deux, la règle de variation est insatisfiable dès la
// troisième reprise.
//
// ── La version mélangée du modèle, et pourquoi elle commande tout le reste ──
//
// Le point à relire en premier, parce qu'une première rédaction s'y était
// trompée. L'extramission ne se présente presque jamais, à 13-14 ans, sous sa
// forme stricte (« seul mon œil fait le travail »). Elle se présente sous la
// forme MÉLANGÉE, celle que le champ `conception` déclare en toutes lettres :
// la lumière est admise, elle éclaire la scène, et ce qui fait que je vois,
// c'est ce qui part de mon œil vers ce que je vise. C'est le stade 3 des
// quatre de Guesne (`didactique.md` § 6.3), et Cottrell & Winer 1994 (✔, § 6.2)
// le confirment par le complément : c'est une minorité de 6th graders qui NIE
// que quelque chose entre dans l'œil — la majorité l'accorde, et dessine
// malgré tout des flèches sortantes. Le chiffre exact reste dans
// `didactique.md`, il n'a rien à faire ici et rien du tout à faire dans ce qui
// est servi à l'élève.
//
// Conséquence, et c'est elle qui décide de la rédaction du `controle` et des
// exécutions : tout dispositif fondé sur l'ABSENCE DE LUMIÈRE est muet sur la
// version mélangée. Dans le noir, cet élève prédit « je ne vois rien » — et il
// a raison, pour la raison qu'il croit. Un dispositif qui lui annonce ensuite
// « ton modèle prédisait le ballon » lui dit quelque chose de faux sur son
// propre modèle, et il le sait : il repart conforté, ce qui est exactement le
// pire des trois cas. Deux exécutions sur trois doivent donc mettre en défaut
// les DEUX versions, et le `controle` doit contenir un test qui tranche même
// quand l'élève a correctement dessiné une lampe et un objet éclairé. Ce test
// est ici « as-tu déjà vu quelque chose AVANT de l'avoir regardé ? » : le
// modèle, dans ses deux versions, l'interdit ; la vision périphérique le fait
// tous les jours.
//
// Les deux autres pièges ne partagent PAS cet empêchement, et le prétendre
// serait un renoncement gratuit : la diffusion par les objets ordinaires et
// l'absence de transport de matière par le son se constatent tous les deux,
// prédiction verrouillée d'abord. Ils portent donc de vrais constats, plus un
// contre-modèle de décor distinct pour la variation.
//
// ── La dépendance entre les deux pièges de lumière, et ce qui la porte ─────
//
// Même défaut que la version mélangée, sur l'autre piège, et il a fallu deux
// corrections. Le contrôle de la diffusion tenait dans un seul geste : « je le
// vois, donc de la lumière en est partie vers mon œil ». Le geste est juste, et
// il est MUET sur exactement un élève : celui qui tient encore l'extramission,
// pour qui voir n'est pas recevoir et qui répond donc « non, c'est mon œil qui
// travaille ». Le contrôle glissait sur lui sans le contredire. Le même défaut
// frappait plus fort le contre-modèle, qui annonçait à l'élève que son modèle
// « prédit l'invisibilité de tout ce qu'il regarde » : c'est faux, son modèle ne
// prédit rien de tel — il ne contient aucune chaîne de vision — et lui dire cela
// est à la fois un mensonge sur son modèle et une négation de la première des
// deux choses toujours vraies (sa conception prédit correctement son quotidien).
//
// Les deux dispositifs ont donc été redécorés sur le même principe : ne rien
// faire prédire de ce qui est VU, tout faire prédire de l'endroit où la lumière
// ARRIVE. Le contrôle porte une seconde branche — l'objet éclaire-t-il ce qui
// est à côté de lui ? —, et le contre-modèle fait prédire le dessous d'une main
// tenue au-dessus d'une page éclairée. Aucun des deux ne demande de théorie de
// la vision, et tous deux mordent sur les deux élèves.
//
// Reste que la RÈGLE de la diffusion, elle, se justifie par la chaîne de vision
// (« si la table n'en renvoyait pas, tu ne la verrais pas »). L'ordre compte
// donc : `extramission` doit être rencontré avant
// `objets-ordinaires-ne-diffusent-pas`. C'est la même nature de dépendance que
// celle qu'Andersson établit entre la matérialité du gaz et la conservation de
// la masse, et l'invariant 14 code celle-là EN DUR, nommément. AUCUN champ ne
// porte celle-ci : les `rythmeInitial` (4 contre 9) la produisent par accident,
// pas par contrainte. C'est une réserve, pas un dispositif.
//
// ── Deux points d'attention pour le moteur ─────────────────────────────────
//
// (a) `extramission` est le seul piège de rang 1 de la famille — les deux
//     autres sont des rangs 3, voir la note de rang plus haut.
//     L'invariant 14 exige qu'un piège de rang 1 apparaisse dans au moins deux
//     chapitres POSTÉRIEURS à son chapitre d'origine. Décompte exact, corrigé :
//     `programme.md` numérote onze chapitres et range à part deux blocs
//     optionnels, que `charte.md` v2 promeut en « chapitres frontière de plein
//     droit » — treize chapitres, 69 savoir-faire de noyau et 17 de frontière.
//     Le chapitre 9 a donc QUATRE chapitres après lui, pas deux : 10
//     (interactions et forces), 11 (l'Univers), puis la loi d'Ohm et le couple
//     poids/pesanteur. Et les quatre sont marqués [F]. C'est très exactement le
//     cas que le garde-fou de l'interrupteur prévoit, et le corps du minimum est
//     plus fragile qu'il n'y paraît : il n'existe AUCUN chapitre de noyau après
//     le 9, donc un élève qui répond « pas encore » aux chapitres frontière
//     ferait disparaître en silence la re-confrontation du piège qui justifie
//     toute l'architecture. Cette famille est celle où le garde-fou porte, et il
//     n'est pas décoratif ici.
//
// (b) La charte écrit « au moins deux constats (ou deux exécutions de
//     contre-modèle) » ; l'invariant 14, lui, n'écrit que « constats ». Un
//     contrôle rédigé au pied de la lettre refuserait `extramission`, qui est
//     précisément le piège pour lequel la clause entre parenthèses a été
//     écrite. Le contrôle doit lire `constats` ET `contreModele.executions`.
//
// ── Ce que cette famille ne couvre PAS, et pourquoi ─────────────────────────
//
//   • Les ombres (formation, direction). `didactique.md` § 6.3 les signale
//     comme une conséquence de la même conception — la lumière vue comme une
//     source et non comme quelque chose qui se propage — mais sans aucun
//     chiffre et sans typologie séparée. Un piège d'ombre serait un piège
//     inventé, et un piège inventé vaut moins que pas de piège.
//   • « Signal et information ». `didactique.md` § 6.5 : rien. Pas « pas de
//     difficulté » : NON DOCUMENTÉ. Aucun piège, et la rubrique doit le dire à
//     l'élève. Le savoir-faire correspondant du chapitre 9 porte donc
//     `diagnostic: absent` et s'affiche « couvert, non diagnostiqué ».
//   • Les ondes radio et les autres rayonnements — le seul angle mort du plan
//     face au BO (`programme.md` § 3, ch. 9). Aucune conception documentée :
//     rien à typer tant que le périmètre n'est pas tranché.
//   • La vitesse du son comme grandeur quotient, et le calcul d'une distance à
//     partir d'une durée (savoir-faire 6 du chapitre). `didactique.md` § 8 dit
//     qu'il n'existe RIEN là-dessus côté conceptions ; ce qui échoue à cet
//     endroit relève des pièges de grandeur quotient et d'isolement d'une
//     inconnue, qui portent `origine: mathematique` et vivent dans la famille
//     mathématique du catalogue. Les trois pièges d'ici sont tous
//     `origine: physique` : aucun renvoi vers `maths-4e` ne part de ce fichier.
//   • La réfraction, les couleurs, la fréquence et les ultrasons : hors 4e.
//
// ── Ce que ce fichier ne porte pas, et qu'un contrôle refusera ─────────────
//
// La charte liste `distracteurs` parmi les champs obligatoires d'un piège
// (« chacun rattaché à un modèle erroné exécutable si quantitatif »,
// invariant 11). Aucun des trois n'en porte : les distracteurs s'écrivent avec
// les items, et les items n'existent pas. Manque daté, pas oubli — écrit ici
// pour que l'invariant 1 le trouve, exactement comme `symbolique.js` le fait
// pour ses quatre. Aucun `source` non plus, là où `mouvement.js` en porte un
// par piège : les provenances sont dans l'en-tête et dans les notes de rang,
// ce qui est lisible pour un humain et illisible pour le contrôleur.
//
// Et le mot « exécuté » du contre-modèle est un abus, qu'il vaut mieux écrire
// ici que laisser croire. `charte.md` § « Le dialogue après l'erreur » dit du
// modèle erroné qu'il « est *exécutable*, donc son verdict n'est pas rédigé à la
// main », et son exemple est quantitatif : deux lectures d'ampèremètre
// calculées. Ici, `modele` et `predictionDuModele` sont de la PROSE. La
// prédiction du modèle de l'élève a été dérivée par l'auteur, à la main, et rien
// ne la revérifie. L'invariant 11 ne mord pas — il ne contraint que les
// distracteurs QUANTITATIFS, et aucun des trois pièges d'ici n'est quantitatif —
// mais un invariant qui ne mord pas ne rend pas la promesse vraie. Ce qu'on a
// réellement, ce sont des contre-modèles RELUS, de classe C, et c'est ainsi
// qu'il faudra les compter.
//
// Et la forme des champs n'est pas encore unique — mais l'écart s'est réduit
// depuis la première rédaction, et le décrire faux serait pire que de se taire.
// Les familles sont QUATRE, pas trois : `mouvement.js`, `symbolique.js`,
// `electricite.js` et celle-ci. `mouvement.js` portait
// `{ champs, predicat: CHAÎNE, enClair }` — un prédicat en texte, donc
// inexécutable, donc auto-satisfait ; il a depuis adopté la forme d'ici et le
// dit dans son en-tête. Restent DEUX formes :
// `{ situation, predicat: fonction, pourquoi }` ici et dans `mouvement.js`, une
// FONCTION NUE dans `symbolique.js` et `electricite.js`. À trancher au schéma
// `piege.schema.json` ; la forme d'ici est celle qui porte à la fois le type de
// la `situation` et un prédicat exécutable, donc celle qui satisfait
// l'invariant 15 (« dérivée de l'objet situation et non d'un drapeau ») sans
// exiger d'évaluer une chaîne de caractères.
//
// ── Le ton, qui n'est pas décoratif ────────────────────────────────────────
//
// Deux choses toujours vraies, et elles doivent transparaître dans les
// `raisonnements` : la conception de l'élève prédit correctement la
// quasi-totalité de ses situations quotidiennes, et il devra apprendre à
// l'INHIBER plutôt qu'à l'oublier — c'est ce que font les experts (Masson
// 2012). On n'écrit jamais « c'est faux, voilà la règle », et on accorde ce
// qui est vrai AVANT de corriger. La troisième phrase — « des savants l'ont
// cru » — n'est servie que par `antecedentHistorique`, qui n'existe ici que
// pour l'extramission. Servie partout, elle fabriquerait de l'histoire des
// sciences.

