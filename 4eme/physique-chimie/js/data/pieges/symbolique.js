// portent 6. Le quatrième, `formule-substance-ou-entite`, porte **4** — le
// rythme d'un rang 1, sur un piège de rang 2, et il n'y a pas de reliquat
// là-dedans : c'est le seul piège `primaire` du fichier, celui que la seule
// série française du corpus chiffre au plus bas, et ralentir sa reprise parce
// qu'on vient de corriger sa taxonomie serait la conséquence silencieuse type.
// Le rang dit ce qu'on sait de la conception ; le rythme dit la place qu'on
// lui donne. `tester-pieges.mjs` ne refuse que l'inverse — un rang 1 plus lent
// qu'un rang 2 — et l'intervalle grandira de toute façon jusqu'au plafond de
// 20 séances imposé par la charte. Conséquence à ne pas découvrir : ce 4 fait
// de ce piège le rang 2 le plus rapide du catalogue, et la réserve du testeur
// listera donc les rangs 1 des autres familles qui reviennent moins vite que
// lui. Elle a raison de le demander ; elle ne désigne pas une faute de ce
// fichier.

