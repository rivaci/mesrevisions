// Les pièges du REGISTRE SYMBOLIQUE de la chimie — formules et équations.
//
// ── Ce qu'est un piège ici ────────────────────────────────────────────────
//
// Pas une erreur constatée : une conception DOCUMENTÉE. L'élève n'écrit pas
// « 2 H₂O contient 2 atomes d'hydrogène » au hasard — il applique la règle
// qu'on lui a donnée pour lire H₂O, et cette règle est juste. Elle cesse
// seulement de l'être quand un coefficient apparaît devant. Le catalogue
// décrit le modèle, dit d'où on le sait, et dit comment le mettre en défaut.
//
// ── Pourquoi ces quatre-là ────────────────────────────────────────────────
//
// `didactique.md` § 3.7 est la section la mieux servie du dossier côté
// français : Canac & Kermen 2016 (603 sujets dont 233 collégiens) est la
// seule série française récente et chiffrée du corpus, et `didactique.md` la
// marque ✔. Une réserve, portée ici parce que cette source porte à elle seule
// la seule fiabilité `primaire` du fichier : la même ligne précise que les
// chiffres sont « repris dans » une page de vulgarisation de l'ENS. Le ✔ n'est
// donc pas hors d'atteinte de l'épisode du « 57 % », et c'est une raison de
// plus pour qu'aucun de ces chiffres ne descende dans ce fichier. Elle mesure
// une chose : la capacité à dire si une formule désigne la substance ou
// l'entité. Elle est ici le piège n° 1.
//
// Ces chiffres ne se rangent d'ailleurs ni par état de la matière ni par
// familiarité du corps : le taux le plus bas de la série est celui d'un
// liquide organique, le plus haut celui d'un gaz courant. Le `contexteImpose`
// du piège n° 1 impose donc la VARIÉTÉ des états, et non un état privilégié —
// il affirmait le contraire, et l'affirmation ne tenait pas devant la série.
//
// La même section liste ensuite les « erreurs typées sur l'équation,
// directement transposables en pièges ». Trois sont retenues : le `+`, la
// flèche, coefficient/indice. Elles couvrent la totalité de ce que la
// consigne demandait à cette famille.
//
// ── Ce que la famille NE couvre PAS, et pourquoi ──────────────────────────
//
// - **L'ajustement d'une équation.** `programme.md` § 3 : « Aucun attendu de
//   fin de cycle n'est fixé en termes d'ajustement d'une équation de
//   réaction. » En 4ᵉ l'élève LIT une équation fournie et déjà ajustée.
//   Aucun item de cette famille ne demande d'équilibrer quoi que ce soit, et
//   aucune règle ne s'appuie sur l'équilibrage comme sur un acquis.
// - **L'écriture d'une équation à partir d'un énoncé** : hors collège.
// - **Le schéma particulaire** (dessiner ce que dit une équation) : c'est le
//   registre SUBMICROSCOPIQUE, il appartient à la famille « matière ». Ici on
//   ne quitte jamais le symbole et son référent.
// - **Les ions et les espèces chargées** : 3ᵉ (`programme.md`).
// - **La nomenclature** (« nommer O₂ ») : c'est un savoir-faire, pas une
//   conception ; s'y tromper n'est pas appliquer un modèle, c'est ne pas
//   savoir.
// - **« CH₂O lu comme du carbone lié à de l'eau », « H₂O, OH₂ et HOH jugées
//   non identiques »** (Keig & Rubba, cités par `didactique.md` § 3.7) :
//   aucune donnée sur 12-14 ans, et aucun mécanisme distinct de ceux déjà
//   couverts par `formule-substance-ou-entite` et
//   `coefficient-et-indice-confondus`. Un piège inventé vaut moins que pas
//   de piège : ils ne sont pas écrits.
// - **La mole et le nombre d'Avogadro** : hors cycle 4. Aucun constat ne s'y
//   appuie, même quand ce serait spectaculaire.
//
// ── Les rangs : ce qui est repris, ce qui est dérivé ──────────────────────
//
// **`didactique.md` § 7 ne range AUCUNE conception de cette famille.** Les
// quatre du rang 1 sont l'extramission, la conservation de la masse,
// l'adhérence force-vitesse et le courant qui s'use ; les cinq du rang 2
// sont électriques, particulaires ou classificatoires. Le registre
// symbolique n'apparaît qu'au § 8, sous « solidement établi ». Aucun rang
// ci-dessous n'est donc une reprise littérale : les quatre sont DÉRIVÉS, et
// voici la dérivation, pour qu'un relecteur puisse la refuser.
//
// **Les quatre sont de rang 2**, et le premier ne l'a pas toujours été : il a
// été écrit rang 1, et la relecture adverse a refusé la dérivation. Elle est
// gardée ici avec ce qui l'a fait tomber, pour qu'on puisse la refuser à son
// tour.
//
// - `formule-substance-ou-entite` → **rang 2**. La dérivation refusée était
//   celle-ci : le critère du § 7 est « persistance mesurée après un
//   enseignement qui la visait explicitement » ; Canac & Kermen mesurent la
//   réussite du collège à l'université et concluent qu'il n'y a « pas
//   d'amélioration significative selon le niveau ». Trois choses la
//   défont. D'abord, ce n'est pas une persistance mesurée CONTRE un
//   enseignement ciblé mais À TRAVERS un enseignement ordinaire : la
//   dérivation le reconnaissait déjà (« ce n'est pas le protocole de
//   Winer »), et le critère du § 7, lui, ne connaît pas de degrés. Ensuite,
//   ce fichier affirme deux cents lignes plus bas le contraire de ce que le
//   critère exige : le raisonnement `jamais-demande` répond à l'élève
//   « personne ne te l'avait demandé, c'est même la question qu'on saute le
//   plus souvent en chimie ». Si l'enseignement ne pose jamais la question,
//   il n'existe aucun enseignement qui la vise explicitement, et le critère
//   du rang 1 n'a pas d'objet — la conception ne résiste pas à un
//   enseignement, elle n'en rencontre aucun. Enfin le coût : le plafond de
//   dix pièges de rang 1 de `charte.md` est **déjà atteint** par les quatre
//   familles écrites (`index.js` le dit), et la conservation de la masse,
//   elle nommément rangée au § 7 ②, n'est pas écrite. Un rang 1 dérivé qui
//   occupe la dernière place en coûte cinq créneaux par an à un rang 1
//   documenté.
//   Ce qui reste vrai, et qui ne dépend pas du rang : c'est le seul piège
//   `primaire` du fichier, celui que la seule série française du corpus
//   chiffre au plus bas, et son `rythmeInitial` ne bouge pas (voir plus bas).
// - Le motif du rang 2, pour les quatre, et il n'est pas un motif par
//   défaut : un mécanisme de production est nommable, et il est le nôtre. C'est le motif exact que
//   `didactique.md` § 7 applique à la pile-générateur-constant (Dupin &
//   Johsua : produite par l'insistance mise sur la conservation du courant).
//   Ici, l'application enseignera nécessairement la formule comme un décompte
//   d'atomes dans une molécule, la conservation des atomes et de la masse, et
//   l'indice avant le coefficient : elle fabriquera donc ces quatre lectures
//   chez des élèves qui ne les avaient pas encore. Le champ `iatrogene` porte
//   à chaque fois le savoir-faire producteur, et la charte impose alors la
//   programmation APRÈS lui. Deux pièges partagent le même producteur
//   (`ch05-sf4-interpreter-formule-chimique`) et c'est le même geste qui les
//   fait : ce savoir-faire n'installe pas seulement « le petit chiffre compte
//   les atomes », il installe que la formule parle de la molécule et de rien
//   d'autre.
//   **C'est une hypothèse de mécanisme, pas un résultat de `didactique.md`.**
//   Aucune des quatre n'y est rangée, et le rang 2 n'y est pas non plus une
//   affaire de mesure (l'entrée « les analogies » y est marquée ○). À
//   invalider sur élève-pilote si elles se révèlent absentes avant le
//   chapitre 6 — pour la première, avant le chapitre 5.
//
// Le rang 3 n'est employé nulle part : il signifie « cède effectivement à
// cet âge », donc « on n'y dépense pas d'effort ». Rien dans le dossier ne
// permet de l'affirmer d'une conception de cette famille, et l'affirmer à
// tort la retirerait de la file de réfutation.
//
// ── Les fiabilités ────────────────────────────────────────────────────────
//
// Convention `didactique.md` : ✔ → primaire, ◆ → secondaire, ○ →
// non-documente. Un seul piège est `primaire` : celui que Canac & Kermen
// chiffre. Les trois autres sont **`non-documente`** — `didactique.md` les
// nomme (Dehon & Snauwaert 2015 pour coefficient/indice), mais sans chiffre,
// sans marqueur de fiabilité qui leur soit propre, et sans donnée sur la
// tranche 12-14 ans. Le ✔ qui ferme la liste des erreurs typées porte sur
// Marais & Jordaan (les treize étapes d'interprétation), pas sur les puces
// qui précèdent : on ne le leur étend pas. Conséquence de charte : aucun de
// ces trois ne peut fonder à lui seul une décision de maîtrise.
//
// ── Les chiffres ──────────────────────────────────────────────────────────
//
// Les taux de réussite mesurés au collège sont l'argument qui justifie cette
// famille. **Aucun ne figure dans un texte servi à l'élève** — ni dans une
// `regle`, ni dans un `controle`, ni dans un `raisonnement`, ni dans un
// constat : tout ce que l'application affiche est lu par un élève et par
// personne d'autre. Ils restent dans `didactique.md`, qui est le seul endroit
// où ils sont accompagnés de leur provenance. C'est la règle issue de
// l'épisode du « 57 % d'ampèremètre » : un chiffre de seconde main devenu
// argument servi. La borne basse et la borne haute sont citées plus haut dans
// cet en-tête sans leur valeur, pour la même raison — un commentaire de
// dérivation n'est pas servi, mais il se recopie.
//
// ── L'antécédent historique ───────────────────────────────────────────────
//
// **Aucun piège de cette famille n'en porte, et c'est délibéré.** Le champ
// n'existe que pour le capital force (Viennot : « exactement la théorie
// médiévale de l'impetus ») et l'extramission. Servie ici, la phrase « des
// savants l'ont cru » fabriquerait de l'histoire des sciences : la notation
// chimique moderne date de Berzelius, personne n'a jamais « cru » que la
// flèche était un signe égal, et l'élève n'a pas à être payé en monnaie de
// singe.
//
// ── Le ton, et le test que chaque piège doit passer ───────────────────────
//
// Deux choses toujours vraies, qui doivent transparaître dans les
// `raisonnements` : la lecture de l'élève prédit correctement la
// quasi-totalité de ce qu'on lui demande, et il devra apprendre à
// l'INHIBER, pas à l'oublier. Un chimiste lit toujours « + » comme une
// addition quand il fait ses courses. Il ne l'a pas désappris ; il regarde
// d'abord sur quelle page il est.
//
// Et le test, appliqué à chacun des quatre après rédaction : prendre une
// réponse fausse typique que le piège diagnostique, lui appliquer sa `regle`
// et son `controle`, vérifier qu'ils la CONTREDISENT. Une règle qui reste
// muette, ou pire qui confirme, est le défaut le plus discret du projet.
//
// **Il a mordu quatre fois à la première relecture adverse.** Les corrections
// sont dans le fichier, et les voici pour qu'on puisse les refuser à leur tour :
//  - coefficient/indice : le contrôle « écris les molécules en toutes lettres
//    et compte les H un par un » donne HUIT des deux côtés sur « 4 H₂O et
//    H₈O₄, c'est pareil ». Il confirmait la réponse fausse, sur la comparaison
//    de deux écritures que le `formatDiagnostique` du même piège rend
//    obligatoire. Le contrôle compte désormais les molécules d'abord et dit
//    explicitement que le total d'atomes ne sépare pas ces deux-là.
//  - la flèche : le contrôle « lis la ligne à l'envers, est-ce que ça s'est
//    déjà produit ? » valide « c'est un égal » dès que l'élève pense à une
//    transformation dont l'inverse existe — l'électrolyse de l'eau, que le
//    contre-modèle du même piège cite deux lignes plus bas. Le contrôle ne
//    repose plus sur l'irréversibilité seule, et la `conditionValidite` lit
//    enfin `reversibiliteConnue`, qui était déclarée et morte.
//  - le « + » : le contrôle ne traitait que le membre de gauche. Appliqué à
//    droite, « réagit avec » produit une phrase — donc le verdict « tu lis
//    bien une équation » — et une phrase fausse. Il est maintenant à deux
//    membres, ce que la `regle` disait déjà.
//  - le piège n° 1 : le premier constat coupait un clou en deux, ce qui
//    n'atteint jamais l'atome et ne réfute donc pas la lecture micro, la
//    dominante de Canac & Kermen. Il servait en outre la formule hors de toute
//    phrase, contre le `contexteImpose` du piège lui-même.
//
// **Il a mordu cinq fois de plus à la seconde**, et les cinq sont du même
// genre que les quatre premières — une règle, un contrôle ou une condition qui
// ne réfute que la moitié de ce qu'il vise :
//  - la flèche, le contrôle, encore : « compte les molécules des deux côtés,
//    un égal exigerait le même nombre » n'est un test que dans un sens. Sur
//    CH₄ + 2 O₂ → CO₂ + 2 H₂O — l'équation que ce fichier sert deux pièges
//    plus haut — il y a trois molécules de chaque côté, et l'élève qui compte
//    repart avec sa lecture confirmée. Le contrôle dit maintenant ce que
//    l'égalité des comptes prouve : rien.
//  - la flèche, la condition de validité : elle écartait les atomes et la
//    masse parce qu'ils se conservent, et laissait passer les trois
//    dénombrements sans regarder s'ils DIFFÈRENT sur l'équation servie. Deux
//    molécules et deux espèces de chaque côté, c'est courant. La condition
//    lit désormais les deux comptes, comme la règle force-vitesse de
//    `charte.md` lit les deux signes.
//  - le premier constat du piège n° 1 : réécrit une seconde fois. « Laquelle
//    de ces deux phrases est fautive ? » laissait « aucune des deux »
//    disponible — et c'est ce que répond l'élève qui lit Fe comme une
//    particule, pour qui « 3 g de Fe » veut dire 3 g d'atomes de fer. Bonne
//    réponse, aucun engagement, aucun conflit. Il verrouille maintenant ce
//    que sa conception affirme : que le symbole désigne toujours la même
//    chose.
//  - le « + », le contrôle : corrigé au premier tour sur les deux membres, il
//    restait **infalsifiable**. « Remplace le + de gauche par réagit avec,
//    puis lis à voix haute : si tu entends plusieurs corps, tu lis une
//    équation » — la substitution étant la bonne lecture, elle produit
//    toujours plusieurs corps, donc toujours le verdict « c'est bon ». Un
//    contrôle qui ne peut pas rendre « tu t'es trompé » n'est pas un contrôle,
//    c'est la règle répétée. Le geste qui décide porte maintenant sur le
//    récipient et peut échouer : nomme ce que tu retirerais si tu ne pouvais
//    en enlever qu'un seul. C'est celui des deux constats.
//  - le « + », le contexte imposé : « deux réactifs qui se distinguent à l'œil
//    ou au toucher », et le motif donné pour l'exiger — sur deux gaz incolores
//    « une seule chose » et « deux choses » ont la même tête — est réfuté par
//    le SECOND CONSTAT DU MÊME PIÈGE, où deux gaz incolores se comptent en
//    fermant un robinet. La `conditionValidite` refusait donc l'item que le
//    dispositif de remédiation démontre. Elle connaît maintenant les deux
//    séparateurs, l'apparence et l'arrivée qu'on peut couper.
// Et le rang 1 du piège n° 1 est tombé à la même passe — la dérivation et son
// refus sont plus haut.
//
// ── Ce que ce fichier ne porte pas, et qu'un contrôle refusera ────────────
//
// La charte liste `distracteurs` parmi les champs obligatoires d'un piège
// (« chacun rattaché à un modèle erroné exécutable si quantitatif »,
// invariant 11). Aucun des quatre n'en porte : les distracteurs s'écrivent
// avec les items, et les items n'existent pas. C'est un manque daté, pas un
// oubli ; il est écrit ici pour que l'invariant 1 le trouve plutôt que de le
// découvrir.
//
// **Et un second champ manque, que la première rédaction ne déclarait pas.**
// `charte.md` § « Le lien avec les mathématiques » : « les pièges d'origine
// mathématique portent EN PLUS la section de `maths-4e` vers laquelle
// renvoyer », et l'invariant 18 refuse un renvoi vers une section absente de
// `maths-4e/public/sections.json`, dont la version est figée sous le nom
// `CONTRAT_MATHS`. `fleche-lue-comme-egal` porte `origine: 'mathematique'` et
// aucun renvoi. La cible existe pourtant — `4eme/maths` porte bien le piège
// jumeau `affectation-lue-comme-egalite`, au chapitre 17 — mais l'artefact
// versionné, lui, n'existe pas : ni `sections.json`, ni `CONTRAT_MATHS`.
// Écrire le renvoi maintenant, ce serait le vérifier contre une cible
// mouvante, exactement ce que la charte a corrigé en versionnant le contrat.
// Le champ est donc absent, et cette absence a une date : la publication de
// `sections.json` côté maths.
//
// Et la forme des champs n'était pas réconciliée avec `mouvement.js`,
// `signaux.js` et `electricite.js`, écrits en parallèle. Ce qui l'est
// désormais, à l'écriture de `index.js` et de `tools/tester-pieges.mjs` : les
// quatre fentes d'un constat, qui portaient quatre vocabulaires pour trois
// idées. Elles s'appellent partout `contexteDeSurface`, `predictionEngagee`,
// `resultat`, `conflit` — le vocabulaire de `charte.md` (« item à prédiction
// engagée »). Ici, c'étaient `predictionDemandee`, `resultatAffiche` et
// `ceQueCaContredit` ; aucun contenu n'a bougé.
//
// Ce qui ne l'est PAS, et qui reste à trancher : `conditionValidite` est ici
// une FONCTION — le contrôle l'exécute sur la `situation`, ce que la charte
// demande (« la condition est dérivée, pas déclarée : le contrôle lit la
// situation, pas le drapeau ») ; dans `mouvement.js` et `signaux.js` c'est un
// objet `{ champs, predicat, enClair }` dont le prédicat est une chaîne à
// évaluer. `formatDiagnostique` est ici un objet, ailleurs une chaîne.
// `mouvement.js` porte en plus `nom` et `source`, que les autres n'ont pas.
// `tester-pieges.mjs` ne vérifie donc que la PRÉSENCE de ces champs, jamais
// leur forme : arbitrer depuis un fichier de tests une question de contenu
// serait la trancher sans la poser.
//
// **Le contre-modèle en fait partie, et la première rédaction l'omettait de
// cette liste — c'est celui des écarts qui a une conséquence.** Il s'appelle
// ici `{ enonceDuModele, execution: [...], lecture }`, dans `signaux.js` et
// `mouvement.js` `{ id, modele, executions: [...] }`, dans `electricite.js`
// `{ enonce, predire, verdict }`. Or `tester-pieges.mjs` lit `executions` au
// pluriel : les dix exécutions de ce fichier ne sont vues par aucun de ses
// contrôles, et le test « toute exécution de contre-modèle engage aussi une
// prédiction avant de la confronter » passe ici **à vide**. Il ne passe pas à
// tort — les quatre pièges tiennent leurs dispositifs de remédiation dans
// leurs `constats`, et l'exécution du modèle n'en est pas un —, mais un test
// vert sans donnée est ce que la charte appelle une garantie ressentie. C'est
// écrit ici plutôt que renommé : renommer alignerait le champ et rendrait
// alors obligatoires, pour chaque exécution, un `contexteDeSurface` et une
// prédiction d'élève que ces exécutions n'ont pas à porter.
//
// Ce qui, en revanche, a été aligné sans attendre l'arbitrage : les deux
// modèles NUMÉRIQUES du fichier portent un `predire`, comme dans
// `electricite.js`. La flèche prédit l'égalité de n'importe quel décompte,
// coefficient/indice prédit l'indice tout court : ces deux-là se calculent,
// donc leur verdict n'a pas à être rédigé à la main — et c'est la même
// fonction qui dit quand le modèle GAGNE, c'est-à-dire quand l'item ne doit
// pas être servi. Les deux autres modèles sont qualitatifs : ce qu'ils
// prédisent est une lecture, pas un nombre, et il n'y a rien à exécuter.
//
// ── Conventions d'identifiants ────────────────────────────────────────────
//
// `chapitreOrigine` et `iatrogene` suivent la convention de nommage de
// `maths/js/data/chapitres/` (chNN-slug), appliquée aux titres et à la
// numérotation de `programme.md` § 3. À réconcilier quand le fichier des
// chapitres de physique-chimie et celui des savoir-faire seront écrits.
//
// `origine` vaut `physique` (lire : « cette matière ») sauf pour la flèche,
// où le symbole en cause est importé de l'algèbre et où l'appli de maths
// porte déjà le piège jumeau, `affectation-lue-comme-egalite` (chapitre 17).
// C'est là, et là seulement, que le renvoi a une cible.
//
// `rythmeInitial` est un RYTHME en séances, jamais une échéance : l'échéance
